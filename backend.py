# ============================================================
# GET AND VALIDATE THE POSTGRESQL DATABASE URL
# ============================================================

def get_database_url():
    """
    Read the PostgreSQL connection URL from environment variables.

    Steps:
    1. Read DATABASE_URL from the .env file/environment.
    2. Raise an error if the URL is missing.
    3. Add sslmode=require if it is not already specified.
    4. Return the final database URL.
    """
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise ValueError(
            "DATABASE_URL is missing. Please add your Render PostgreSQL External Database URL to .env"
        )

    if "sslmode=" not in database_url:
        separator = "&" if "?" in database_url else "?"
        database_url = f"{database_url}{separator}sslmode=require"

    return database_url

# ============================================================
# LOAD AND VALIDATE THE GROQ API KEY
# ============================================================
GROQ_API_KEY = os.getenv("GROQ_API_KEY")
if not GROQ_API_KEY:
    raise ValueError("GROQ_API_KEY is missing. Please add it to your .env file.")

# ============================================================
# STEP 22: INITIALIZE THE GROQ LANGUAGE MODEL
# ============================================================
llm = ChatGroq(
    model="qwen/qwen3.8-27b",
    api_key=GROQ_API_KEY,
    max_tokens=800
)

# ============================================================
# DEFINE THE SHARED TRAVEL STATE
# ============================================================
class TravelState(TypedDict):
    """
    Defines the structure of the shared state used by LangGraph.

    Each field stores information that different workflow nodes
    can read or update while planning a trip.
    """
    messages: Annotated[list[AnyMessage], operator.add]
    user_query: str
    flight_results: str
    hotel_results: str
    itinerary: str
    llm_calls: int

# ============================================================
# CREATE THE FLIGHT-SEARCH AGENT NODE
# ============================================================
def flight_agent(state: TravelState):
    """
    Search for flight information using the user's travel request.

    Input:
        state: The shared LangGraph state containing user_query,
               messages, flight_results, itinerary, and llm_calls.

    Returns:
        A dictionary containing updates to the shared state.
    """
    query = state["user_query"]
    flight_data = search_flights(query)

    return {
        "flight_results": flight_data,
        "messages": [
            AIMessage(content="Flight results fetched.")
        ],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

# ============================================================
# STEP 25: CREATE THE HOTEL-SEARCH AGENT NODE
# ============================================================

def hotel_agent(state: TravelState):
    """
    Search the web for hotel recommendations related to the
    user's travel request.

    Input:
        state: Shared LangGraph state containing the user's query
               and existing conversation information.

    Returns:
        A dictionary containing hotel-search results and
        updates to the conversation state.
    """
    query = f"Best hotels for {state['user_query']}"
    hotel_results = tavily_search(query)

    return {
        "hotel_results": hotel_results,
        "messages": [
            AIMessage(content="Hotel information fetched.")
        ],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

# ============================================================
# CREATE THE ITINERARY GENERATION AGENT
# ============================================================

def itinerary_agent(state: TravelState):
    """
    Generate a travel itinerary using the user's request,
    flight-search results, and hotel-search results.

    Input:
        state: Shared LangGraph state containing the travel
               request and results from previous agents.

    Returns:
        A dictionary containing the generated itinerary,
        the AI response message, and an updated call counter.
    """
    prompt = f"""
        Create a complete travel itinerary.

        User Query:
        {state['user_query']}

        Flight Results:
        {state['flight_results']}

        Hotel Results:
        {state['hotel_results']}

        Make the itinerary practical, budget-aware, and easy to follow.
        """

    response = llm.invoke([
        SystemMessage(content="You are an expert travel planner."),
        HumanMessage(content=prompt)
    ])

    return {
        "itinerary": response.content,
        "messages": [response],
        "llm_calls": state.get("llm_calls", 0) + 1
    }

# ============================================================
# CREATE THE FINAL RESPONSE AGENT
# ============================================================

def final_agent(state: TravelState):
    """
    Generate the final, user-facing travel-planning response.

    Input:
        state: Shared LangGraph state containing the original
               user request, flight results, hotel results,
               and generated itinerary.

    Returns:
        A dictionary containing the final AI response message
        and the updated LLM call counter.
    """
    final_prompt = f"""
        Generate the final travel response for the user.

        User Request:
        {state['user_query']}

        Flights:
        {state['flight_results']}

        Hotels:
        {state['hotel_results']}

        Itinerary:
        {state['itinerary']}

        Format the final answer beautifully using these sections:

        1. Trip Summary
        2. Flight Information
        3. Hotel Suggestions
        4. Day-by-Day Itinerary
        5. Estimated Budget
        6. Final Recommendations

        Important:
        - Be clear and practical.
        - Mention that live flight API may not provide ticket prices if pricing is unavailable.
        - Keep the response useful for real travel planning.
        
        """

    response = llm.invoke([
        SystemMessage(content="You are a professional AI travel booking assistant."),
        HumanMessage(content=final_prompt)
    ])

    return {
        "messages": [response],
        "llm_calls": state.get("llm_calls", 0) + 1
    }


# ============================================================
# BUILD THE TRIPMATE AI AGENT WORKFLOW
# ============================================================
graph = StateGraph(TravelState)

graph.add_node("flight_agent", flight_agent)
graph.add_node("hotel_agent", hotel_agent)
graph.add_node("itinerary_agent", itinerary_agent)
graph.add_node("final_agent", final_agent)

graph.add_edge(START, "flight_agent")
graph.add_edge("flight_agent", "hotel_agent")
graph.add_edge("hotel_agent", "itinerary_agent")
graph.add_edge("itinerary_agent", "final_agent")
graph.add_edge("final_agent", END)

# ============================================================
# CONFIGURE POSTGRESQL CHECKPOINTING
# ============================================================
DATABASE_URL = get_database_url()

# ------------------------------------------------------------
# CONNECT TO THE POSTGRESQL DATABASE
# ------------------------------------------------------------
_conn = psycopg.connect(
    DATABASE_URL,
    autocommit=True,
    row_factory=dict_row
)

# ------------------------------------------------------------
# CREATE THE LANGGRAPH CHECKPOINTER
# ------------------------------------------------------------
checkpointer = PostgresSaver(_conn)
checkpointer.setup()

# ------------------------------------------------------------
# COMPILE THE GRAPH WITH CHECKPOINTING ENABLED
# ------------------------------------------------------------
travel_graph = graph.compile(checkpointer=checkpointer)


# ============================================================
# RUN THE TRIPMATE AI TRAVEL AGENT
# ============================================================
def run_travel_agent(user_input: str, thread_id: str | None = None):
    if not thread_id:
        thread_id = f"user_{uuid.uuid4().hex}"

    config = {
        "configurable": {
            "thread_id": thread_id
        }
    }

    result = travel_graph.invoke(
        {
            "messages": [
                HumanMessage(content=user_input)
            ],
            "user_query": user_input,
            "flight_results": "",
            "hotel_results": "",
            "itinerary": "",
            "llm_calls": 0
        },
        config=config
    )

    final_answer = result["messages"][-1].content

    return {
        "thread_id": thread_id,
        "answer": final_answer,
        "flight_results": result.get("flight_results", ""),
        "hotel_results": result.get("hotel_results", ""),
        "itinerary": result.get("itinerary", ""),
        "llm_calls": result.get("llm_calls", 0),
    }